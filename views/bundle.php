<?php
/** GET /c/{token}/bundle?type=bank|regulator&to=... — print-oriented evidence bundle (server-rendered). */
$token = strtoupper($seg[1] ?? '');
if (!CancelStack\Token::valid($token)) {
    http_response_code(404);
    require __DIR__ . '/404.php';
    return;
}
$pdo = cs_db();
$st = $pdo->prepare('SELECT * FROM cases WHERE token = ?');
$st->execute([$token]);
$case = $st->fetch();
if (!$case) {
    http_response_code(404);
    require __DIR__ . '/404.php';
    return;
}
$st = $pdo->prepare(
    'SELECT * FROM attempts WHERE case_id = ? ORDER BY attempt_date ASC, logged_at ASC, id ASC'
);
$st->execute([$case['id']]);
$attempts = $st->fetchAll();

$type = ($_GET['type'] ?? 'bank') === 'regulator' ? 'regulator' : 'bank';
$to   = trim((string)($_GET['to'] ?? ''));
$docType = $type === 'regulator'
    ? 'REGULATOR COMPLAINT ATTACHMENT'
    : 'BANK CHARGEBACK DISPUTE PACK';
$today = date('F j, Y');

// facts table rows
$facts = [
    ['Merchant',            e($case['merchant'])],
    ['Plan / product',      e($case['plan'] ?: '—')],
    ['Amount',              $case['amount'] !== null ? '$' . number_format((float)$case['amount'], 2) : '—'],
    ['Billing cycle',        e($case['cycle'] ?: '—')],
    ['Subscription started', e($case['started'] ?: '—')],
    ['Merchant reference',  e($case['ref'] ?: '—')],
    ['Case reference',      e($case['token'])],
];
$caseStatus = CancelStack\Status::fromOutcomes(array_column($attempts, 'outcome'));
$facts[] = ['Current case status', e($caseStatus)];

// timeline entries
$entries = '';
$i = 0;
foreach ($attempts as $a) {
    $i++;
    $conf = $a['confirmation'] ? '<p><strong>Confirmation:</strong> ' . e($a['confirmation']) . '</p>' : '';
    $shot = $a['screenshot_url']
        ? '<p><strong>Screenshot reference:</strong> <a href="' . e($a['screenshot_url']) . '" rel="noopener">' . e($a['screenshot_url']) . '</a></p>'
        : '';
    $note = $a['note'] ? '<p class="b-note">' . nl2br(e($a['note'])) . '</p>' : '';
    $d = date('F j, Y', strtotime($a['attempt_date']));
    $entries .= <<<E
<div class="b-entry">
  <p class="b-entry-head"><span class="mono">{$d}</span> — Attempt {$i}</p>
  <p><strong>Channel:</strong> {$a['channel']} &nbsp;&nbsp;<strong>Outcome:</strong> {$a['outcome']}</p>
  {$conf}{$note}{$shot}
</div>
E;
}
if ($attempts === []) {
    $entries = '<p>No attempts logged yet.</p>';
}

// screenshot reference list (numbered)
$shots = [];
foreach ($attempts as $a) {
    if ($a['screenshot_url']) {
        $shots[] = $a['screenshot_url'];
    }
}
$shotList = '';
if ($shots) {
    $shotList = '<h2 class="h2">Screenshot references</h2><ol class="b-shots">';
    $n = 0;
    foreach ($shots as $u) {
        $n++;
        $shotList .= '<li><a href="' . e($u) . '" rel="noopener">' . e($u) . '</a></li>';
    }
    $shotList .= '</ol>';
}

$toLine = $to !== '' ? '<p class="b-to">Prepared for: ' . e($to) . '</p>' : '';
$home = app_url();
echo <<<HTML
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>Cancellation evidence record — {$case['token']}</title>
<link rel="stylesheet" href="{$home}/assets/css/app.css">
</head>
<body class="bundle-body">
<main class="wrap b-wrap">
  <div class="b-head">
    <h1>CANCELLATION EVIDENCE RECORD</h1>
    <p class="b-doc">{$docType}</p>
    <p>Case reference: <span class="mono">{$case['token']}</span></p>
    <p>Generated: <span class="mono">{$today}</span></p>
    {$toLine}
  </div>

  <h2 class="h2">Subscription facts</h2>
  <table class="b-facts">
HTML;
foreach ($facts as [$k, $v]) {
    echo '<tr><th>' . e($k) . '</th><td>' . $v . '</td></tr>';
}
echo <<<HTML
  </table>

  <h2 class="h2">Cancellation attempt timeline (chronological)</h2>
  {$entries}

  {$shotList}

  <footer class="b-foot">
    <p>Generated by CancelStack on {$today}. Records are user-entered and timestamped at entry.</p>
    <button class="btn btn-primary no-print" onclick="window.print()">Print / Save as PDF</button>
    <p class="no-print"><a href="{$home}/c/{$case['token']}">Back to the case timeline</a></p>
  </footer>
</main>
</body>
</html>
HTML;
