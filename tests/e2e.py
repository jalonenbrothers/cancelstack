#!/usr/bin/env python3
"""CancelStack e2e checks against a running Apache (BASE env or localhost:8099)."""
import json, os, sys, urllib.request, urllib.error, urllib.parse

BASE = os.environ.get("CS_BASE", "http://localhost:8099")
results = []

def call(method, path, body=None):
    req = urllib.request.Request(BASE + path, method=method)
    data = None
    if body is not None:
        data = json.dumps(body).encode()
        req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, data) as r:
            return r.status, json.loads(r.read())
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read())

def get(path):
    with urllib.request.urlopen(BASE + path) as r:
        return r.status, r.read().decode()

def check(name, cond):
    results.append(bool(cond))
    print(("ok  - " if cond else "FAIL - ") + name)

# 1. create case
s, c = call("POST", "/api/case", {"merchant": "GymHub Pro", "plan": "Premium Monthly",
    "amount": "29.99", "cycle": "monthly", "started": "2026-06-15", "ref": "ACCT-77",
    "tried": "Called the number on the site, sat through retention offers, no confirmation email."})
tok = c.get("token", "")
check("create case 201 + 10-char token", s == 201 and len(tok) == 10)

# 2. get case
s, g = call("GET", "/api/case/" + tok)
check("get case 200", s == 200)
check("tried -> attempt #1 auto-created", len(g.get("attempts", [])) == 1)
check("status In progress", g["case"]["status"] == "In progress")
check("case_url in create response", "case_url" in c)

# 3. add attempts
s, a1 = call("POST", "/api/case/%s/attempt" % tok, {"date": "2026-10-28", "channel": "phone",
    "outcome": "spoke-to-human", "note": "Agent said cancelled but offered 3 retention deals."})
check("add attempt 201", s == 201)
s, a2 = call("POST", "/api/case/%s/attempt" % tok, {"date": "2026-10-30", "channel": "web portal",
    "outcome": "success", "confirmation": "CN-4471", "screenshot_url": "https://imgur.com/cancelproof"})
check("add success attempt 201", s == 201)

s, g = call("GET", "/api/case/" + tok)
check("status now Cancelled", g["case"]["status"] == "Cancelled")
check("3 attempts, newest first (today's auto attempt first)", len(g["attempts"]) == 3
      and g["attempts"][0]["attempt_date"] >= "2026-10-30")

# 4. edit the success attempt -> still-charged flips status to Disputed
s, g = call("GET", "/api/case/" + tok)
success = [a for a in g["attempts"] if a["outcome"] == "success"]
check("success attempt exists", len(success) == 1)
aid = success[0]["id"]
s, _ = call("PATCH", "/api/attempt/%d" % aid, {"date": "2026-10-30", "channel": "web portal",
    "outcome": "still-charged", "confirmation": "CN-4471", "screenshot_url": "https://imgur.com/cancelproof"})
check("PATCH edit 200", s == 200)
s, g = call("GET", "/api/case/" + tok)
edited = [a for a in g["attempts"] if a["id"] == aid][0]
check("status flips to Disputed", g["case"]["status"] == "Disputed")
check("outcome updated", edited["outcome"] == "still-charged")

# 5. validation
s, _ = call("POST", "/api/case", {"merchant": ""})
check("empty merchant 422", s == 422)
s, _ = call("POST", "/api/case/%s/attempt" % tok, {"date": "2030-01-01", "channel": "phone", "outcome": "other"})
check("future date 422", s == 422)
s, _ = call("GET", "/api/case/XXXXXXXXX")
check("bad token 404", s == 404)

# 6. pages render
for path in ["/", "/case/new", "/about", "/c/" + tok, "/c/" + tok + "/export"]:
    st, body = get(path)
    check("GET %s 200 html" % path, st == 200 and "<html" in body.lower())

q = urllib.parse.urlencode({"type": "regulator", "to": "Ohio AG Consumer Protection"})
st, b = get("/c/%s/bundle?%s" % (tok, q))
check("bundle 200", st == 200)
check("bundle doc type regulator", "REGULATOR COMPLAINT ATTACHMENT" in b)
check("bundle recipient line", "Ohio AG Consumer Protection" in b)
check("bundle facts table", "Subscription facts" in b)
check("bundle chronological detail", "Attempt 1" in b and "CN-4471" in b)
check("bundle screenshot refs", "Screenshot references" in b and "imgur.com/cancelproof" in b)
check("bundle footer", "Generated by CancelStack" in b)

# 7. blocked internal paths under real Apache
for path in ["/lib/config.php", "/lib/bootstrap.php", "/src/Validator.php",
             "/migrations/001_cancelstack.sql", "/tests/run.php", "/config.example.php"]:
    try:
        urllib.request.urlopen(BASE + path)
        check("blocked %s" % path, False)
    except urllib.error.HTTPError as e:
        check("blocked %s -> %d" % (path, e.code), e.code in (403, 404))

# 8. invalid token page (I is excluded from the token alphabet)
try:
    st, p404 = get("/c/ABCDEFGHIJ")
    check("invalid token page: Case not found copy", "Case not found" in p404)
except urllib.error.HTTPError as e:
    body = e.read().decode()
    check("invalid token page: Case not found copy", e.code == 404 and "Case not found" in body)

fails = len(results) - sum(results)
print("\n%d/%d e2e checks passed" % (sum(results), len(results)))
print("TOKEN:", tok)
sys.exit(1 if fails else 0)
